#!/usr/bin/env bash
# build.sh - the only build script: one language, one quoting regime, no PowerShell.
#
# Run it from an MSYS2 "MinGW64" shell, or let CI run it:
#     bash build/build.sh
# It writes the version into include/version.h (the single source of truth for the
# version string), generates the version info into the .rc, then compiles and links
# dist/desktop-slideshow.exe and zips it with a default slideshow.ini.
set -euo pipefail
cd "$(dirname "$0")/.."

VER="${DSKV_VERSION:-$(sed -n 's/.*DSKV_VERSION_STR L"\(.*\)".*/\1/p' include/version.h 2>/dev/null || true)}"
VER="${VER:-0.1.0}"

command -v g++      >/dev/null || { echo "g++ not found - open an MSYS2 MinGW64 shell"; exit 1; }
command -v windres  >/dev/null || { echo "windres not found - install mingw-w64-x86_64-binutils"; exit 1; }
command -v zip      >/dev/null || echo "zip not found - the .zip will be skipped"

# ---- version: one file, read by the sources, parsed for the .rc ----
printf '// regenerated by build/build.sh - do not edit\n#pragma once\n#define DSKV_VERSION_STR L"%s"\n' "$VER" > include/version.h

IFS='.' read -r V1 V2 V3 V4 _ <<EOF
${VER}.0.0.0.0
EOF
V1=${V1:-0}; V2=${V2:-0}; V3=${V3:-0}; V4=${V4:-0}
VDOT="$V1.$V2.$V3.$V4"

mkdir -p dist

# ---- resources: icon + manifest + version info ----
# The version reaches the .rc by replacing two @TOKEN@ placeholders (see src/app.rc),
# so no quote ever passes through a shell argument - that is what broke CI runs #7/#8.
VCOMMA="$V1,$V2,$V3,$V4"
sed -e "s/@VERCOMMA@/$VCOMMA/" -e "s/@VERDOT@/$VDOT/" src/app.rc > src/app-generated.rc
if ! windres -i src/app-generated.rc -O coff -o dist/app.res; then
    rm -f src/app-generated.rc
    echo "windres failed" >&2
    exit 1
fi
rm -f src/app-generated.rc

# ---- compile + link ----
CXXFLAGS="-std=c++17 -O2 -s -Wall -Wextra -Wno-unused-parameter -municode -mwindows -DUNICODE -D_UNICODE"
LDFLAGS="-Wl,--subsystem,windows"
LIBS="-lgdiplus -lcomctl32 -lshell32 -lwtsapi32 -luser32 -lgdi32 -lole32 -loleaut32 -luuid -lkernel32 -ladvapi32"
SOURCES="src/main.cpp src/app.cpp src/config.cpp src/images.cpp src/render.cpp src/cli.cpp"
EXE="dist/desktop-slideshow.exe"

echo "== g++ $VER"
if ! g++ $CXXFLAGS $LDFLAGS -static -static-libgcc -static-libstdc++ $SOURCES dist/app.res -o "$EXE" $LIBS; then
    # No static runtime in this MinGW: link against the DLLs and ship them along.
    echo "== static link failed, retrying with the dynamic runtime"
    g++ $CXXFLAGS $LDFLAGS $SOURCES dist/app.res -o "$EXE" $LIBS
    RUNTIME=1
else
    RUNTIME=0
fi

# ---- portable zip ----
rm -rf dist/stage && mkdir -p dist/stage
cp "$EXE" dist/stage/
if [ "$RUNTIME" = 1 ]; then
    for dll in libgcc_s_seh-1.dll libstdc++-6.dll libwinpthread-1.dll; do
        [ -f "/mingw64/bin/$dll" ] && cp "/mingw64/bin/$dll" dist/stage/ || true
    done
fi
[ -f slideshow.default.ini ] && cp slideshow.default.ini dist/stage/slideshow.ini || true
for doc in README.md LICENSE; do [ -f "$doc" ] && cp "$doc" dist/stage/ || true; done

if command -v zip >/dev/null; then
    rm -f "dist/desktop-slideshow-$VDOT-win-x64-portable.zip"
    ( cd dist/stage && zip -q -9 "../desktop-slideshow-$VDOT-win-x64-portable.zip" ./* )
    ( cd dist && sha256sum "desktop-slideshow-$VDOT-win-x64-portable.zip" > "desktop-slideshow-$VDOT-win-x64-portable.SHA256.txt" )
fi

ls -l dist
echo "built dist/desktop-slideshow.exe ($VER)"
